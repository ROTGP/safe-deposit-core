import { test, expect, beforeEach } from 'vitest'
import sd from '../../src/safeDeposit'

beforeEach(async () => {
    await sd.init()
})

// https://datatracker.ietf.org/doc/html/rfc3394#page-30
test('hash (Blake2b)', async () => {

    let input = sd.fromHex('000102030405060708090a0b0c0d0e0f101112131415161718191a1b1c1d1e1f202122232425262728292a2b2c2d2e2f303132333435363738393a3b3c3d')
    let output = sd.simpleHash(input, 64)
    let expectedOutput = sd.fromHex('5c6bbf16baa180f986bd40a1287ed4c549770e7284858fc47bc21ab95ebbf3374b4ee3fd9f2af60f3395221b2acc76f2d34c132954049f8a3a996f1e32ec84e5')

    input = sd.fromHex('000102030405060708090a0b0c0d0e0f101112131415161718191a1b1c1d1e1f202122232425262728292a2b2c2d2e2f303132333435363738393a3b3c3d3e3f404142434445464748494a4b4c4d4e4f505152535455565758595a5b5c5d5e5f606162636465666768696a6b6c6d6e6f707172737475767778797a7b7c7d7e7f808182838485868788898a8b8c8d8e8f909192939495969798999a9b9c9d9e9fa0a1a2a3a4a5')
    output = sd.simpleHash(input, 64)
    expectedOutput = sd.fromHex('57a34f2bcca60d4b85103b830c9d7952a416be5263ae429c9e5e53fe8590a8f78ec65a51109ea85dcdf7b6223f9f2b340539fad81923dbf8edabf95129e4dff6')
    expect(output).toEqual(expectedOutput)

    let key = sd.fromHex('000102030405060708090a0b0c0d0e0f101112131415161718191a1b1c1d1e1f202122232425262728292a2b2c2d2e2f303132333435363738393a3b3c3d3e3f')
    input = sd.fromHex('000102030405060708090a0b0c0d0e0f101112131415161718191a1b1c1d1e1f202122232425262728292a2b2c2d2e2f30')
    output = sd.simpleHash(input, 64, key)
    expectedOutput = sd.fromHex('14d4d40d5984d84c5cf7523b7798b254e275a3a8cc0a1bd06ebc0bee726856acc3cbf516ff667cda2058ad5c3412254460a82c92187041363cc77a4dc215e487')
    expect(output).toEqual(expectedOutput)
})